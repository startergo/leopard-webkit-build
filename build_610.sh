            # (WebCore only) the literal "SOVERSION" token CMake emits before we
            # normalize the on-disk Versions dir to A in phase8 above.  Rewrite
            # BOTH to the absolute system path so DYLD_FRAMEWORK_PATH redirects
            # them exactly like the 604 reference -- an unrewritten SOVERSION
            # dep would point at a Versions/SOVERSION dir that no longer exists.
            for VTOK in A SOVERSION; do
                install_name_tool -change "@rpath/$DEP.framework/Versions/$VTOK/$DEP" \
                    "/System/Library/Frameworks/$DEP.framework/Versions/A/$DEP" "$B" 2>/dev/null || true
                install_name_tool -change "@loader_path/../../../../../PrivateFrameworks/$DEP.framework/Versions/$VTOK/$DEP" \
                    "/System/Library/Frameworks/$DEP.framework/Versions/A/$DEP" "$B" 2>/dev/null || true
            done
        done
    done

    # Strip build-tree LC_RPATH entries.  CMake bakes $BUILD_DIR/lib in so
    # @rpath deps resolve during in-tree linking -- but it's a dead local
    # path on the 10.6 target (and wrong, like the 604 reference had it too).
    # No dep uses @rpath after the rewrites above, so these rpaths are pure
    # dead weight; delete every one that lives under the build tree.
    for FW in JavaScriptCore WebCore WebKitLegacy WebKit; do
        local B="$FW_DIR/$FW.framework/Versions/A/$FW"
        [ -f "$B" ] || B="$FW_DIR/$FW.framework/$FW"
        [ -f "$B" ] || continue
        otool -l "$B" 2>/dev/null \
            | awk '/cmd LC_RPATH/{g=1} g&&/path /{sub(/^.*path /,"");sub(/\(offset.*$/,"");gsub(/^[[:space:]]+|[[:space:]]+$/,"");print;g=0}' \
            | while IFS= read -r rp; do
                case "$rp" in
                    "$BUILD_DIR"*) install_name_tool -delete_rpath "$rp" "$B" 2>/dev/null || true ;;
                esac
            done
    done

    # Runtime dylibs.
    info "  Copying runtime libraries..."
    [ -f "$LIBCXX_DIST/lib/libc++.1.dylib" ] && cp "$LIBCXX_DIST/lib/libc++.1.dylib" "$FW_DIR/"
    [ -f "$LIBCXX_DIST/lib/libc++abi.dylib" ] && cp "$LIBCXX_DIST/lib/libc++abi.dylib" "$FW_DIR/"

    echo "$VERSION" > "$RES_DIR/VERSION"
    echo "$VERSION-snowleopard-605" > "$RES_DIR/BRANCH"
    cat > "$RES_DIR/start.html" <<STARTEOF
<html><head><title>WebKit Snow Leopard</title></head>
<body><h1>WebKit ${VERSION} for Mac OS X 10.6 Snow Leopard</h1>
<p>Modern WebKit (safari-610.1.15-branch) built for Snow Leopard x86_64,
with minimal 10.6-targeted compatibility patches.</p></body></html>
STARTEOF

    ok "WebKit.app packaged ($(du -sh "$APP" | awk '{print $1}'))"
}

