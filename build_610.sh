#!/bin/bash
# ==========================================================================
#  build_605.sh — Reproducible build of WebKit 605 for Mac OS X 10.6 Snow Leopard
#
#  Branch:  safari-610.1.15-branch @ 638989847985af550947c53986514adebf9f0d02
#  Target:  Mac OS X 10.6 Snow Leopard x86_64 (cross-compiled from Apple Silicon)
#  Outputs: JavaScriptCore.framework, WebCore.framework, WebKitLegacy.framework
#           → packaged as WebKit.app → WebKit-610.1.15-SnowLeopard-x86_64.dmg
#
#  Differences from build.sh (604):
#   • NO Leopard community patch (WebKit_604.5.6.diff / supplement.diff). Instead a
#     few small, branch-specific patches in patches-610/ (OptionsMac.cmake guard,
#     feature flags, Metal/WebGPU source exclusion). 605 targets 10.6 x86_64
#     directly — it does not need the 10.5/PowerPC ATS/font/gradient hacks.
#   • WebKitSystemInterface (WSI) is eliminated in 605 → no wk_stubs, no
#     WebKitLibraries link path. The PAL SPI layer replaces WSI.
#   • ENABLE_WEBKIT=OFF: the WK2 tree (Network/StorageProcess, WebKit) is not
#     built. We build JSC + WebCore + WebKitLegacy, then package WebKitLegacy
#     into the WebKit.framework slot for Safari 5.1 on 10.6.
#   • 605-specific SPI symbols provided in sdk_stubs_605.mm:
#       _CFAppVersionCheckLessThan, _NSRecommendedScrollerStyle() (as a function,
#       not the variable the 604 stubs used), NSWindowWillOrder{On,Off}ScreenNotification.
#
#  Reuse: the SDK-compat overlay header (TargetConditionals_compat.h + sub-headers)
#  and the dependency tree (dist/: ICU 55, libc++ 5.0.1, crt) are pure 10.6-SDK
#  artifacts — identical for 604 and 605 — so they are shared with build.sh's
#  build/overlay-includes/ and dist/ rather than duplicated. (If absent, generate
#  once with `./build.sh --patches` then interrupt after Phase 3.)
#
#  Usage:
#    ./build_605.sh              # full build → DMG (idempotent per phase)
#    ./build_605.sh --clean      # wipe build-610/ + re-apply patches, rebuild
#    ./build_605.sh --patches    # (re)apply 605 patches only
#    ./build_605.sh --package-only  # only run packaging phases 8-10
#
#  A first-pass 605 build will surface 10.6-SDK breaks the audits did not
#  enumerate (they diffed 604→605, not the full 10.6 surface). Iterate the
#  patches in patches-610/ as ninja reports them. See audit §16.
# ==========================================================================

set -euo pipefail

# ── Configuration ──────────────────────────────────────────────────────────
PROJECT_ROOT="$(cd "$(dirname "$0")" && pwd)"
SDK_NAME="MacOSX10.6.sdk"
SDK_DIR="$PROJECT_ROOT/sdk/MacOSX-SDKs/$SDK_NAME"

SOURCE_DIR="$PROJECT_ROOT/sources_610"          # 605 source (pinned branch)
BUILD_DIR="$PROJECT_ROOT/build-610"             # 605 build tree (separate from 604)
STAMP_DIR="$BUILD_DIR/stamps"
PATCH_DIR="$PROJECT_ROOT/patches-610"           # minimal branch-dependent patches
VERSION="610.1.15"

# Shared SDK-compat overlay (generated by build.sh phase 3; pure 10.6-SDK shim)
OVERLAY_DIR="$PROJECT_ROOT/build/overlay-includes"

# Shared dependency tree (ICU + libc++ + crt) — branch-independent
DOWNLOADS_DIR="$PROJECT_ROOT/downloads"
DIST_DIR="$PROJECT_ROOT/dist"
ICU_SRC="$DOWNLOADS_DIR/icu62-src/icu"  # [leopard] ICU 62.2 to match WebKit 610 bundled headers
ICU_DIST="$DIST_DIR/icu"
CRT_DIST="$DIST_DIR/crt"
LIBCXX_SRC="$DOWNLOADS_DIR/llvm-project/libcxx"
LIBCXXABI_SRC="$DOWNLOADS_DIR/llvm-project/libcxxabi"
LIBCXX_DIST="$DIST_DIR/libcxx"

TARGET="x86_64-apple-macos10.6"
ARCH="x86_64"

RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'; CYAN='\033[0;36m'; NC='\033[0m'
info()  { echo -e "${CYAN}[INFO]${NC}  $*"; }
ok()    { echo -e "${GREEN}[OK]${NC}    $*"; }
warn()  { echo -e "${YELLOW}[WARN]${NC}  $*"; }
err()   { echo -e "${RED}[ERROR]${NC} $*" >&2; }

CLEAN=false; PATCHES_ONLY=false; PACKAGE_ONLY=false
for arg in "$@"; do
    case "$arg" in
        --clean)        CLEAN=true ;;
        --patches)      PATCHES_ONLY=true ;;
        --package-only) PACKAGE_ONLY=true ;;
        -h|--help) sed -n '2,40p' "$0"; exit 0 ;;
        *) err "Unknown argument: $arg"; exit 1 ;;
    esac
done

# ── Phase 0: Prerequisites ─────────────────────────────────────────────────
phase0_prerequisites() {
    info "Phase 0: Checking prerequisites..."

    for tool in cmake ninja clang clang++; do
        command -v "$tool" >/dev/null 2>&1 || { err "'$tool' not found. Install: brew install cmake ninja"; exit 1; }
    done
    ok "Build tools found"

    # SDK
    if [ ! -d "$SDK_DIR/usr/include" ]; then
        local SDK_LINK="$PROJECT_ROOT/sdk/$SDK_NAME"
        if [ -d "$SDK_LINK/usr/include" ]; then SDK_DIR="$SDK_LINK"
        else err "Mac OS X 10.6 SDK not found at $SDK_DIR"; exit 1; fi
    fi
    ok "10.6 SDK: $SDK_DIR"

    # 605 source
    if [ ! -d "$SOURCE_DIR/.git" ]; then
        err "605 source not found at $SOURCE_DIR. Clone with:"
        err "  git clone --depth 1 -b safari-610.1.15-branch \\"
        err "    https://github.com/WebKit/WebKit.git $SOURCE_DIR"
        err "  cd $SOURCE_DIR && git fetch --depth 1 origin 638989847985af550947c53986514adebf9f0d02 && git checkout FETCH_HEAD"
        exit 1
    fi
    ok "605 source: $SOURCE_DIR"

    # Shared SDK-compat overlay header (pure 10.6-SDK shim, generated by build.sh)
    if [ ! -f "$OVERLAY_DIR/TargetConditionals_compat.h" ]; then
        err "Shared SDK-compat overlay missing: $OVERLAY_DIR/TargetConditionals_compat.h"
        err "It is a pure 10.6-SDK header shared with build.sh. Generate it once:"
        err "  ./build.sh --patches   (then interrupt after 'Phase 3' completes)"
        exit 1
    fi
    if [ ! -f "$OVERLAY_DIR/sdk_stubs.mm" ]; then
        err "Shared sdk_stubs.mm missing under $OVERLAY_DIR (run ./build.sh --patches once)."
        exit 1
    fi
    ok "Shared overlay: $OVERLAY_DIR"

    # CRT startup files
    if [ ! -f "$CRT_DIST/crt1.o" ]; then
        local SYS_SDK="/Library/Developer/CommandLineTools/SDKs/MacOSX.sdk"
        if [ -f "$SYS_SDK/usr/lib/crt1.o" ]; then
            info "  Extracting CRT startup files from system CLT..."
            mkdir -p "$CRT_DIST"
            cp "$SYS_SDK"/usr/lib/crt1.o "$CRT_DIST/"
            cp "$SYS_SDK"/usr/lib/crt1.10.5.o "$CRT_DIST/" 2>/dev/null || true
            cp "$SYS_SDK"/usr/lib/crt1.10.6.o "$CRT_DIST/" 2>/dev/null || true
        else
            warn "CRT startup files not found; executable linking may fail."
        fi
    fi

    mkdir -p "$BUILD_DIR" "$STAMP_DIR" "$BUILD_DIR/cmake"
}

# ── Phase 1: Dependencies (shared dist/ — ICU 55 + libc++ 5.0.1) ────────────
phase1_icu() {
    if [ -f "$ICU_DIST/lib/libicuuc.a" ]; then info "ICU: present (shared dist/)"; return 0; fi
    info "Phase 1a: Building ICU 62.2 for x86_64..."
    mkdir -p "$ICU_DIST"; cd "$ICU_SRC/source"
    CC="clang -arch $ARCH" CXX="clang++ -arch $ARCH -std=c++11" \
    CFLAGS="-arch $ARCH -O2" CXXFLAGS="-arch $ARCH -O2 -std=c++11" LDFLAGS="-arch $ARCH" \
    AR=/usr/bin/ar RANLIB=/usr/bin/ranlib \
    ./configure --host=x86_64-apple-darwin --prefix="$ICU_DIST" \
        --enable-static --disable-shared --disable-samples --disable-tests --disable-renaming --with-data-packaging=static
    make -j"$(sysctl -n hw.ncpu)" 2>&1 | tail -5
    make install 2>&1 | tail -5
    cd "$PROJECT_ROOT"; ok "ICU 62.2 built"
}

phase1_libcxx() {
    if [ -f "$LIBCXX_DIST/lib/libc++.1.dylib" ]; then info "libc++: present (shared dist/)"; return 0; fi
    info "Phase 1b: Building libc++abi 5.0.1..."
    mkdir -p "$LIBCXX_DIST/lib" "$LIBCXX_DIST/include"
    local TF="-target $ARCH-apple-macos10.6 -isysroot $SDK_DIR -fallow-unsupported"
    cd "$LIBCXXABI_SRC/lib"; rm -f *.o
    for FILE in ../src/*.cpp; do
        local BASE="$(basename "$FILE")"
        [ "$BASE" = "cxa_demangle.cpp" ] && continue
        [ "$BASE" = "cxa_noexception.cpp" ] && continue
        clang++ -c -O2 $TF -std=c++11 -nostdinc++ -isystem "$LIBCXX_SRC/include" -I../include \
            -DNDEBUG -DHAVE___CXA_THREAD_ATEXIT_IMPL -D_LIBCPP_DISABLE_AVAILABILITY \
            -Wno-sign-conversion -Wno-shadow -Wno-conversion -Wno-shorten-64-to-32 "$FILE"
    done
    printf '%s\n' \
      'int __cxa_thread_atexit_impl(void(*dtor)(void*), void* obj, void* dso) { return -1; }' \
      'char* __cxa_demangle(const char* mangled, char* buf, unsigned long* n, int* status) { return 0; }' > _stub.c
    clang -c -O2 $TF -DNDEBUG _stub.c -o _stub.o
    clang $TF -o libc++abi.dylib -dynamiclib -nodefaultlibs \
        -current_version 5.0.1 -compatibility_version 1 -install_name /usr/lib/libc++abi.dylib -lSystem *.o
    cp libc++abi.dylib "$LIBCXX_DIST/lib/"

    info "Phase 1c: Building libc++ 5.0.1..."
    cd "$LIBCXX_SRC/src"; rm -f *.o
    for FILE in *.cpp; do
        clang++ -c -O2 $TF -std=c++11 -nostdinc++ -isystem "$LIBCXX_SRC/include" \
            -I"$LIBCXXABI_SRC/include" -DLIBCXX_BUILDING_LIBCXXABI -DNDEBUG \
            -D_LIBCPP_DISABLE_AVAILABILITY "$FILE" 2>/dev/null || true
    done
    clang++ $TF -o "$LIBCXX_DIST/lib/libc++.1.dylib" -dynamiclib -nodefaultlibs \
        -current_version 1.0.5 -compatibility_version 1 -install_name /usr/lib/libc++.1.dylib \
        -L"$LIBCXX_DIST/lib" -lc++abi -lSystem *.o
    ( cd "$LIBCXX_DIST/lib" && ln -sf libc++.1.dylib libc++.dylib )
    info "  Installing libc++ headers..."
    cp -R "$LIBCXX_SRC/include/" "$LIBCXX_DIST/include/"
    cp "$LIBCXXABI_SRC/include/cxxabi.h" "$LIBCXX_DIST/include/"
    cp "$LIBCXXABI_SRC/include/__cxxabi_config.h" "$LIBCXX_DIST/include/"
    cd "$PROJECT_ROOT"; ok "libc++ 5.0.1 built"
}

# ── Phase 2: Apply minimal branch-dependent 605 patches ────────────────────
phase2_patches() {
    local stamp="$STAMP_DIR/patches-applied"
    if [ -f "$stamp" ] && ! $CLEAN; then info "Patches: already applied (stamp exists)"; return 0; fi
    rm -f "$stamp"

    info "Phase 2: Applying minimal 605 patches (NO Leopard community patch)..."

    # Restore source to clean state so patches apply idempotently.
    ( cd "$SOURCE_DIR" && git checkout -- . 2>/dev/null && git clean -fd -- Source/ 2>/dev/null ) || true

    if [ ! -d "$PATCH_DIR" ] || [ -z "$(ls -A "$PATCH_DIR"/*.patch 2>/dev/null)" ]; then
        err "No patches found in $PATCH_DIR/*.patch"; exit 1
    fi

    local APPLIED=0
    for patch in "$PATCH_DIR"/*.patch; do
        # [leopard] The sl-port-610 branch HEAD already contains every patch's
        # change as committed source (the patches are historical build-up
        # artifacts). A patch may therefore be: (a) cleanly reverse-applicable
        # (exactly applied) -> skip; (b) cleanly forward-applicable (pristine
        # base) -> apply; or (c) neither, because the committed file carries
        # ADDITIONAL changes beyond this patch (e.g. WebCoreView.m, ScrollAnimator)
        # so neither direction is clean -> the intent is already in the source,
        # skip with a note rather than failing the build.
        if ( cd "$SOURCE_DIR" && git apply --reverse --check "$patch" ) 2>/dev/null; then
            info "  skipping $(basename "$patch") (already applied)"
            continue
        fi
        if ( cd "$SOURCE_DIR" && git apply --check "$patch" ) 2>/dev/null; then
            info "  applying $(basename "$patch")"
            ( cd "$SOURCE_DIR" && git apply --whitespace=nowarn "$patch" ) \
                || { err "Failed to apply $(basename "$patch") (forward-check passed but apply failed)"; exit 1; }
            APPLIED=$((APPLIED + 1))
        else
            warn "  skipping $(basename "$patch") (neither forward nor reverse applies; committed source already carries the change)"
        fi
    done
    ok "Applied $APPLIED patch(es) from $PATCH_DIR"
    touch "$stamp"
}

# ── Phase 3: Generate 605 runtime stubs ────────────────────────────────────
# Derive sdk_stubs_605.mm from the proven 604 sdk_stubs.mm (shared overlay) and
# append the 605 SPI deltas. Also emit protocol/ehtype stubs (no WSI wk_stubs).
phase3_stubs() {
    local stamp="$STAMP_DIR/stubs-generated"
    [ -f "$stamp" ] && { info "Stubs: already generated"; return 0; }
    rm -f "$stamp"
    info "Phase 3: Generating 605 runtime stubs..."

    local CM="$BUILD_DIR/cmake"
    local OV605="$PROJECT_ROOT/patches-610/overlay"

    # Use the curated 605 stubs directly (NOT derived from the 604 sdk_stubs.mm).
    # 605 has no WSI, calls _NSRecommendedScrollerStyle as a FUNCTION (not the
    # variable the 604 stubs used), resolves NSScrollerImp/NSScrollerImpPair via
    # dynamic_lookup→nil (correct: no overlay scrollers on 10.6), and needs XPC,
    # sandbox, dispatch_data and private AppKit stubs the 604 base lacks. These
    # files were iterated to compile-clean against the 10.6 SDK (see git log).
    cp "$OV605/sdk_stubs_605.mm" "$CM/sdk_stubs_605.mm"

    # Install the whole 605 overlay tree (Overlay605Supplement.h + mach/ shims
    # like vm_page_size.h) into a local overlay dir, force-included / -I'd in
    # phase 4 so it is found before the (incomplete) 10.6 SDK headers.
    mkdir -p "$BUILD_DIR/overlay"
    cp -R "$OV605/." "$BUILD_DIR/overlay/"

    # protocol_stubs.m — formal 10.7+ protocols (informal on 10.6).
    cat > "$CM/protocol_stubs.m" <<'PROTO_EOF'
@protocol NSObject
@end
@protocol NSURLConnectionDelegate <NSObject>
@optional
- (void)connection:(id)connection didFailWithError:(id)error;
- (void)connection:(id)connection didReceiveResponse:(id)response;
- (void)connection:(id)connection didReceiveData:(id)data;
- (void)connection:(id)connection willSendRequest:(id)request redirectResponse:(id)redirectResponse;
- (void)connectionDidFinishLoading:(id)connection;
@end
@interface NSObject <NSObject>
@end
@interface _NSURLConnectionDelegateProtocolHolder : NSObject <NSURLConnectionDelegate>
@end
@implementation _NSURLConnectionDelegateProtocolHolder
@end
PROTO_EOF

    # ehtype_stubs.c — ObjC exception typeinfo for DYLD_FRAMEWORK_PATH redirect.
    cat > "$CM/ehtype_stubs.c" <<'EHTYPE_EOF'
struct _objc_typeinfo { void *vtable[2]; const char *name; };
static struct _objc_typeinfo _ehtype_id_data = {{0, 0}, "id"};
static struct _objc_typeinfo _ehtype_nsexception_data = {{0, 0}, "NSException"};
struct _objc_typeinfo *OBJC_EHTYPE_id = &_ehtype_id_data;
struct _objc_typeinfo *OBJC_EHTYPE_$_NSException = &_ehtype_nsexception_data;
void __objc_personality_v0(void) {}
EHTYPE_EOF

    echo '/* WebKit2 re-export stub - no symbols needed */' > "$CM/webkit2_reexport.c"

    # Overlay605Supplement.h — the NSScrollerStyle / NSScrollerKnobStyle TYPE
    # typedefs (absent from the 10.6 SDK).  605's PAL SPI header
    # pal/spi/mac/NSScrollerImpSPI.h uses them as property/parameter types
    # (lines 56/59/116/145/154); 604 never needed them (WSI, not PAL).  TC_compat
    # only #defines the constant VALUES (NSScrollerStyleLegacy); this header
    # supplies the enum TYPES, force-included into every WebKit TU in phase 4.
    cp "$PATCH_DIR/overlay/Overlay605Supplement.h" "$CM/Overlay605Supplement.h"

    info "  Compiling stubs..."
    # -F sub-framework paths mirror the WebCore CMake flags: on the 10.6 SDK,
    # CoreGraphics/CoreText are sub-frameworks of ApplicationServices and only
    # resolve via these search paths (needed for the CTFontDrawGlyphs fallback).
    clang++ -target $ARCH-apple-macos10.6 -arch $ARCH -isysroot "$SDK_DIR" \
        -I"$OVERLAY_DIR" -stdlib=libc++ -nostdinc++ -isystem "$LIBCXX_DIST/include" \
        -F"$SDK_DIR/System/Library/Frameworks/ApplicationServices.framework/Frameworks" \
        -c "$CM/sdk_stubs_605.mm" -o "$CM/sdk_stubs_605.o" \
        -fallow-unsupported -std=gnu++14 2>&1 | tail -5
    clang -target $ARCH-apple-macos10.6 -arch $ARCH -c "$CM/protocol_stubs.m" -o "$CM/protocol_stubs.o" 2>&1 | tail -3
    clang -target $ARCH-apple-macos10.6 -arch $ARCH -c "$CM/ehtype_stubs.c" -o "$CM/ehtype_stubs.o" 2>&1 | tail -3

    # [leopard] leopard_compat.mm + objc_class_stubs.m provide 10.6 compat shims
    # (libobjc/AppKit class stubs) that phase4 links into every framework via
    # LINKER_FLAGS. They live in the 605 overlay (copied to $BUILD_DIR/overlay
    # above); compile them into $CM so the link finds them. leopard_compat.mm
    # gets the same C++/libc++/sub-framework flags as sdk_stubs_605.mm.
    cp "$OV605/leopard_compat.mm" "$CM/leopard_compat.mm"
    cp "$OV605/objc_class_stubs.m" "$CM/objc_class_stubs.m"
    clang++ -target $ARCH-apple-macos10.6 -arch $ARCH -isysroot "$SDK_DIR" \
        -I"$OVERLAY_DIR" -stdlib=libc++ -nostdinc++ -isystem "$LIBCXX_DIST/include" \
        -F"$SDK_DIR/System/Library/Frameworks/ApplicationServices.framework/Frameworks" \
        -c "$CM/leopard_compat.mm" -o "$CM/leopard_compat.o" \
        -fallow-unsupported -std=gnu++14 2>&1 | tail -5
    clang -target $ARCH-apple-macos10.6 -arch $ARCH -isysroot "$SDK_DIR" \
        -I"$OVERLAY_DIR" -c "$CM/objc_class_stubs.m" -o "$CM/objc_class_stubs.o" \
        -fallow-unsupported 2>&1 | tail -3

    touch "$stamp"
    ok "605 runtime stubs generated"
}

# ── Phase 4: CMake Configure ───────────────────────────────────────────────
phase4_cmake() {
    local stamp="$STAMP_DIR/cmake-configured"
    if [ -f "$stamp" ] && [ -f "$BUILD_DIR/build.ninja" ] && ! $CLEAN; then
        info "CMake: already configured"; return 0
    fi
    rm -f "$stamp"
    info "Phase 4: CMake configure (ENABLE_WEBKIT=OFF — WK2 tree skipped)..."

    local FW_SUBPATHS=(
        "ApplicationServices.framework/Frameworks"
        "CoreServices.framework/Frameworks"
        "Accelerate.framework/Frameworks"
        "Quartz.framework/Frameworks"
        "Carbon.framework/Frameworks"
    )
    local FW_FLAGS=""
    for p in "${FW_SUBPATHS[@]}"; do FW_FLAGS="$FW_FLAGS -F$SDK_DIR/System/Library/Frameworks/$p"; done

    local COMMON_FLAGS="-target $ARCH-apple-macos10.6 -fallow-unsupported"
    COMMON_FLAGS="$COMMON_FLAGS -I$LIBCXX_DIST/include"
    COMMON_FLAGS="$COMMON_FLAGS -I$ICU_DIST/include"
    COMMON_FLAGS="$COMMON_FLAGS -I$OVERLAY_DIR"
    COMMON_FLAGS="$COMMON_FLAGS -include TargetConditionals_compat.h"
    # Overlay605Supplement.h AFTER TC_compat: TC_compat provides the constant
    # VALUES (NSScrollerStyleLegacy); this provides the enum TYPES that the PAL
    # scroller SPI header requires. Plain typedefs (not NS_ENUM) on purpose.
    COMMON_FLAGS="$COMMON_FLAGS -I$BUILD_DIR/overlay -include Overlay605Supplement.h -include AppKitCompat610.h"
    COMMON_FLAGS="$COMMON_FLAGS -D_LIBCPP_DISABLE_EXTERN_TEMPLATE"
    COMMON_FLAGS="$COMMON_FLAGS -DOS_OBJECT_USE_OBJC=0"
    COMMON_FLAGS="$COMMON_FLAGS -DNS_NONATOMIC_IOSONLY=nonatomic"
    COMMON_FLAGS="$COMMON_FLAGS $FW_FLAGS"
    # [leopard] WebCore's 610 ANGLE/WebGL files (platform/graphics/angle/*.cpp,
    # GraphicsContextGL*Cocoa.mm) include <ANGLE/...> and ANGLE-internal headers
    # (<export.h>, entry_points_*). cmake's WebCore target doesn't add ANGLE's
    # source include dirs to the WebCore compile, so add them globally here
    # (matches the dirs ANGLE's own libGLESv2 build uses). Harmless for non-ANGLE TUs.
    COMMON_FLAGS="$COMMON_FLAGS -I$SOURCE_DIR/Source/ThirdParty/ANGLE/include"
    COMMON_FLAGS="$COMMON_FLAGS -I$SOURCE_DIR/Source/ThirdParty/ANGLE/src"
    COMMON_FLAGS="$COMMON_FLAGS -I$SOURCE_DIR/Source/ThirdParty/ANGLE/src/common/third_party/base"
    COMMON_FLAGS="$COMMON_FLAGS -I$BUILD_DIR/Source/ThirdParty/ANGLE/include"
    COMMON_FLAGS="$COMMON_FLAGS -I$SOURCE_DIR/Source/ThirdParty/woff2/include"

    local CXX_FLAGS="$COMMON_FLAGS -std=gnu++14 -Wno-nontrivial-memcall -Wno-missing-template-arg-list-after-template-kw"

    local LINKER_FLAGS="-target $ARCH-apple-macos10.6"
    # NO wk_stubs (WSI eliminated in 605); NO WebKitLibraries link path.
    LINKER_FLAGS="$LINKER_FLAGS $BUILD_DIR/cmake/sdk_stubs_605.o $BUILD_DIR/cmake/leopard_compat.o $BUILD_DIR/cmake/objc_class_stubs.o $BUILD_DIR/cmake/protocol_stubs.o $BUILD_DIR/cmake/ehtype_stubs.o"
    LINKER_FLAGS="$LINKER_FLAGS -L$LIBCXX_DIST/lib"
    LINKER_FLAGS="$LINKER_FLAGS -L$CRT_DIST"
    LINKER_FLAGS="$LINKER_FLAGS -L$ICU_DIST/lib"
    LINKER_FLAGS="$LINKER_FLAGS -licuuc -licui18n -licudata"
    LINKER_FLAGS="$LINKER_FLAGS -Wl,-undefined,dynamic_lookup"
    LINKER_FLAGS="$LINKER_FLAGS -Wl,-reexport_library,/usr/lib/libobjc.A.dylib"
    # NOTE: plain -licu* leaves the static ICU 55 archives unreferenced (ICU
    # symbols leak to the transitive dynamic libicucore), so the linker drops
    # the 25M icudt55 data blob and the frameworks silently fall back to 10.6's
    # ancient system ICU (~4.2) at runtime. We force-load ICU into the JSC and
    # WebCore framework links in phase5_post_cmake (targeted build.ninja
    # surgery) -- NOT here, so WebKitLegacy stays lean (it doesn't use ICU
    # directly, matching the 604 reference's 3.5M WebKitLegacy).

    cd "$BUILD_DIR"

    cmake -G Ninja \
        -DCMAKE_BUILD_TYPE=Release \
        -DCMAKE_POLICY_VERSION_MINIMUM=3.5 \
        -DCMAKE_OSX_ARCHITECTURES="$ARCH" \
        -DCMAKE_SYSTEM_PROCESSOR="$ARCH" \
        -DCMAKE_OSX_SYSROOT="$SDK_DIR" \
        -DCMAKE_C_FLAGS="$COMMON_FLAGS" \
        -DCMAKE_CXX_FLAGS="$CXX_FLAGS" \
        -DCMAKE_SHARED_LINKER_FLAGS="$LINKER_FLAGS" \
        -DCMAKE_EXE_LINKER_FLAGS="$LINKER_FLAGS" \
        -DCMAKE_C_COMPILER_WORKS=ON \
        -DCMAKE_CXX_COMPILER_WORKS=ON \
        -DPORT=Mac \
        -DENABLE_WEBKIT=OFF -DENABLE_TOOLS=OFF \
        -DENABLE_WEBKIT_LEGACY=ON \
        -DENABLE_WEBGPU=OFF \
        -DENABLE_ENCRYPTED_MEDIA=OFF -DENABLE_GPU_PROCESS=OFF \
        -DENABLE_WEBXR=OFF -DENABLE_OFFSCREEN_CANVAS=OFF \
        -DENABLE_WEB_AUTHN=OFF -DENABLE_APPLE_PAY=OFF \
        -DENABLE_PAYMENT_REQUEST=OFF -DENABLE_PICTURE_IN_PICTURE_API=OFF \
        -DENABLE_VIDEO_PRESENTATION_MODE=OFF -DENABLE_RESOURCE_LOAD_STATISTICS=OFF \
        -DENABLE_WEB_API_STATISTICS=OFF -DENABLE_DARK_MODE_CSS=OFF \
        -DENABLE_VARIATION_FONTS=OFF \
        -DENABLE_VIDEO=ON -DENABLE_VIDEO_TRACK=ON -DENABLE_DATACUE_VALUE=OFF -DENABLE_WEB_AUDIO=OFF \
        -DENABLE_MEDIA_STREAM=OFF -DENABLE_MEDIA_CONTROLS_SCRIPT=ON \
        -DENABLE_FULLSCREEN_API=OFF -DENABLE_SMOOTH_SCROLLING=ON -DENABLE_WIRELESS_PLAYBACK_TARGET=OFF \
        -DENABLE_REMOTE_INSPECTOR=OFF -DENABLE_NOTIFICATIONS=OFF \
        -DENABLE_USER_MESSAGE_HANDLERS=OFF -DENABLE_SERVICE_WORKER=OFF \
        -DENABLE_WEBGL=ON -DENABLE_WEBGL2=ON \
        -DENABLE_SUBTLE_CRYPTO=OFF -DENABLE_WEB_CRYPTO=OFF \
        -DENABLE_GEOLOCATION=ON -DENABLE_INDEXED_DATABASE=ON -DENABLE_3D_TRANSFORMS=ON \
        -DENABLE_SERVICE_CONTROLS=OFF -DENABLE_TELEPHONE_NUMBER_DETECTION=OFF \
        -DENABLE_LEGACY_ENCRYPTED_MEDIA=OFF -DENABLE_MEDIA_SOURCE=OFF \
        -DENABLE_ACCELERATED_2D_CANVAS=OFF -DENABLE_CONTENT_FILTERING=OFF \
        -DENABLE_ACCESSIBILITY=ON \
        "$SOURCE_DIR" 2>&1 | tee "$BUILD_DIR/cmake-configure.log"

    [ -f "$BUILD_DIR/build.ninja" ] || { err "CMake failed: build.ninja not generated"; exit 1; }

    # CMake appends the framework version flags (-compatibility_version /
    # -current_version, derived from VERSION/SOVERSION) to our
    # CMAKE_SHARED_LINKER_FLAGS as a CMake LIST element, joining them with a
    # stray ';' — e.g. "...reexport_library,libobjc.A.dylib;-compatibility_version
    # 1 -current_version 602.1.27".  That ';' splits the shell link command in
    # two and the second half ("/bin/sh: -compatibility_version: command not
    # found") fails the framework link.  clang's Darwin driver accepts the bare
    # version flags once they're on the linker's argv, so normalize ';' → ' '
    # before -compatibility_version right after configure.  (Same fix proven on
    # the 604 Leopard build line.)
    if grep -q ';-compatibility_version' "$BUILD_DIR/build.ninja"; then
        sed -i '' 's/;-compatibility_version/ -compatibility_version/g' "$BUILD_DIR/build.ninja"
        info "  Normalized ';' before -compatibility_version in build.ninja"
    fi

    touch "$stamp"
    ok "CMake configured"
}

# ── Phase 5: Post-CMake Fixes ──────────────────────────────────────────────
phase5_post_cmake() {
    local stamp="$STAMP_DIR/post-cmake-fixed"
    if [ -f "$stamp" ] && ! $CLEAN; then info "Post-cmake: already fixed"; return 0; fi
    rm -f "$stamp"
    info "Phase 5: Post-cmake fixes..."

    # Disable features cmake forced ON but that need 10.7+ frameworks.
    local CC="$BUILD_DIR/cmakeconfig.h"
    if [ -f "$CC" ]; then
        for feat in ENABLE_SERVICE_CONTROLS ENABLE_TELEPHONE_NUMBER_DETECTION \
                    ENABLE_LEGACY_ENCRYPTED_MEDIA ENABLE_MEDIA_SOURCE \
                    ENABLE_WEB_AUDIO ENABLE_MEDIA_STREAM \
                    ENABLE_FULLSCREEN_API \
                    ENABLE_REMOTE_INSPECTOR \
                    ENABLE_NOTIFICATIONS ENABLE_USER_MESSAGE_HANDLERS ENABLE_WIRELESS_PLAYBACK_TARGET \
                    ENABLE_SERVICE_WORKER ENABLE_WEBGPU; do
            if grep -q "$feat 1" "$CC"; then
                sed -i '' "s/$feat 1/$feat 0/" "$CC"
                info "  disabled $feat in cmakeconfig.h"
            fi
        done

        # Payment Request API defaults ON (FeatureDefines.h:247) but this
        # branch's binding-generation pass does not emit JSMerchantValidationEvent
        # etc., so EventHeaders.h's #if ENABLE(PAYMENT_REQUEST) #include of a
        # non-existent generated header fails the WebCore compile.  Not needed for
        # a 10.6 WK1 Safari; force OFF by defining it in cmakeconfig.h, which
        # config.h includes before FeatureDefines.h (whose #ifndef guard then
        # honors our 0).  Idempotent.
        grep -q "ENABLE_PAYMENT_REQUEST" "$CC" || \
            perl -i -pe 'print "#define ENABLE_PAYMENT_REQUEST 0\n" if /^#define CMAKECONFIG_H$/' "$CC"
    fi

    local NINJA="$BUILD_DIR/build.ninja"
    if [ -f "$NINJA" ]; then
        # Fix semicolon-joined linker flags (CMake list expansion).
        grep -q ';-compatibility_version' "$NINJA" && sed -i '' 's/;-compatibility_version/ -compatibility_version/g' "$NINJA"
        # Strip host-only framework links absent from the 10.6 SDK.
        for fw in AVFoundation AVFAudio Metal DataDetectorsCore Lookup CoreMedia VideoToolbox; do
            sed -i '' "s|/System/Library/Frameworks/$fw.framework||g; s|/System/Library/PrivateFrameworks/$fw.framework||g" "$NINJA"
            sed -i '' "s/-framework $fw //g; s/-framework $fw\$//g" "$NINJA"
        done
        # The AVFoundation find_library is NOTFOUND on 10.6, so its -iframework flag
        # expands to a broken `-iframework /Versions/Current/Frameworks`; blank it.
        sed -i '' 's|-iframework /Versions/Current/Frameworks||g' "$NINJA"
        # CFNetwork exists in the 10.6 SDK (as a CoreServices sub-framework) but
        # REJECTS direct linking: every product is an LC_SUB_CLIENT of CFNetwork,
        # so `-framework CFNetwork` fails with "cannot link directly with CFNetwork
        # ... product being built is not an allowed client".  Strip the direct LINK
        # flag only; the CoreServices umbrella (already linked) re-exports CFNetwork's
        # symbols and -undefined,dynamic_lookup covers the remainder.  The -F path
        # for header resolution is left intact.
        sed -i '' 's/-framework CFNetwork //g; s/-framework CFNetwork$//g' "$NINJA"

        # Override -fvisibility=hidden → default so ALL ObjC class symbols
        # (_OBJC_CLASS_$_*) are in the export trie.  Modern clang (Xcode 21)
        # with -fvisibility=hidden does NOT put ObjC classes in the export
        # trie, causing "Symbol not found: _OBJC_CLASS_$_*" dyld crashes on
        # 10.6 (system frameworks like SyndicationUI reference WebIconDatabase
        # etc. via two-level namespace binds that dyld resolves from the export
        # trie, not the symbol table).  Default visibility ensures all symbols
        # are exported at the cost of a larger binary.
        sed -i '' 's/-fvisibility=hidden/-fvisibility=default/g' "$NINJA"
        info "  overrode -fvisibility=hidden → default (ObjC class export fix)"

        # Use -O2 instead of -O3: -O3 causes (a) OOM kills on heavy template TUs
        # (the media code with ENABLE(VIDEO) is especially heavy) and (b)
        # elimination of final virtual method overrides, leaving vtable slots
        # as undefined dyld symbols.  -O2 avoids both while still optimizing well.
        sed -i '' 's/ -O3 / -O2 /g' "$NINJA"
        info "  overrode -O3 → -O2 (memory + virtual-method-elimination fix)"

        # Strip redundant /usr/lib/libicucore.dylib references. CMake's
        # find_library(ICU) injects these dynamic refs into BOTH the LINK_LIBRARIES
        # AND the implicit-dependency (| ...) sections of build.ninja. ninja then
        # treats the literal path as a build input it must produce, but it does not
        # exist on the Apple-Silicon host (it is a 10.6 *runtime* path), so ninja
        # aborts: "missing and no known rule to make it". The actual ICU linkage
        # comes from -L$ICU_DIST/lib -licuuc -licui18n -licudata in LINK_FLAGS
        # (and the static force-load above for the two framework edges), so these
        # dynamic refs are pure noise. Strip them everywhere.
        sed -i '' 's#/usr/lib/libicucore\.dylib##g' "$NINJA"
        info "  stripped redundant /usr/lib/libicucore.dylib refs (ninja dep-graph fix)"

        # Force-load the static ICU 55 archives into the JSC and WebCore
        # FRAMEWORK links so their modern data (icudt55l: emoji, Unicode 7/8
        # properties, collation) is EMBEDDED and used at runtime -- 10.6's
        # system libicucore (~ICU 4.2) is far too old for 2018-era WebKit.
        # Plain -licu* leaves the archives unreferenced (ICU symbols leak to
        # the transitive dynamic libicucore) so the linker drops the whole 25M
        # data blob; the framework then silently falls back to ancient system
        # ICU. Scoped to EXACTLY these two framework binary edges (perl
        # paragraph mode); WebKitLegacy stays on dynamic -licu*, matching the
        # 604 reference's lean 3.5M WebKitLegacy (it has no direct ICU use).
        # NB: CMake emits WebCore's framework version dir as a literal
        # "SOVERSION" token, so its edge path differs from JSC's "A".
        perl -00 -i -pe '
            if (/^build lib\/(?:JavaScriptCore\.framework\/Versions\/A\/JavaScriptCore|WebCore\.framework\/Versions\/SOVERSION\/WebCore):/m) {
                s{-licuuc -licui18n -licudata}{-Wl,-force_load,'"$ICU_DIST"'/lib/libicuuc.a -Wl,-force_load,'"$ICU_DIST"'/lib/libicui18n.a -Wl,-force_load,'"$ICU_DIST"'/lib/libicudata.a}g;
            }
        ' "$NINJA"
        info "  force-loaded static ICU 55 into JSC + WebCore framework links"
        info "  scrubbed host-only framework links from build.ninja"
    fi

    # ENABLE_WEBKIT=OFF → no ForwardingHeaders/WebKit (WK2) tree is generated.
    # WebKitLegacy still does `#import <WebKit/...>` in places, so expose the
    # legacy forwarding headers under the WebKit name (do NOT call
    # fix-forwarding-headers.sh — it errors when the WebKit dir is absent).
    local FH="$BUILD_DIR/DerivedSources/ForwardingHeaders"
    if [ -d "$FH/WebKitLegacy" ] && [ ! -e "$FH/WebKit" ]; then
        ln -sf WebKitLegacy "$FH/WebKit"
        info "  linked ForwardingHeaders/WebKit → WebKitLegacy"
    fi

    # ── Freeze build.ninja + repair forwarding headers ────────────────────
    # A stray `ninja` can trigger the live RERUN_CMAKE rule, which regenerates
    # build.ninja (wiping every patch above) AND rewrites the DerivedSources
    # forwarding headers as self-referential `#include "<abs-path-to-self>"`
    # (infinite include -> "#include nested too deeply", then a cascade of
    # bogus DOM/symbol errors). Neuter the regen rule, then normalize every
    # single-line forwarding-header redirect to an ABSOLUTE include of the real
    # source header (framework-preferred, WK2/Windows-penalized).
    local RULES="$BUILD_DIR/CMakeFiles/rules.ninja"
    if [ -f "$RULES" ] && grep -q 'regenerate-during-build' "$RULES"; then
        python3 - "$RULES" <<'PYRULES'
