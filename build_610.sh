    # makehybrid → HFS+/Apple partition scheme, mountable on 10.6 (no APFS/GPT).
    info "  Creating disk image..."
    local HYBRID="$BUILD_DIR/${NAME}_hybrid.dmg"; rm -f "$HYBRID"
    hdiutil makehybrid -hfs -hfs-volume-name "WebKit Snow Leopard" -o "$HYBRID" "$STAGE"
    hdiutil convert "$HYBRID" -format UDZO -o "$DMG" -imagekey zlib-level=9
    rm -f "$HYBRID"; rm -rf "$STAGE"
    ok "DMG created: $DMG ($(ls -lh "$DMG" | awk '{print $5}'))"
}

# ── Main ───────────────────────────────────────────────────────────────────
main() {
    echo "========================================================"
    echo "  WebKit 605 (${VERSION}) for Mac OS X 10.6 Snow Leopard"
    echo "  Cross-compiling: $(uname -m) → x86_64   (ENABLE_WEBKIT=OFF)"
    echo "========================================================"
    echo ""

    if $CLEAN; then
        info "Cleaning 605 build tree..."
        rm -rf "$BUILD_DIR"; mkdir -p "$BUILD_DIR" "$STAMP_DIR" "$BUILD_DIR/cmake"
        ( cd "$SOURCE_DIR" && git checkout -- . 2>/dev/null && git clean -fd -- Source/ 2>/dev/null ) || true
        info "Clean complete."
    fi

    if $PACKAGE_ONLY; then
        info "Skipping phases 0-7 (--package-only)"
    else
        phase0_prerequisites
        phase1_icu
        phase1_libcxx
        phase2_patches
        if $PATCHES_ONLY; then ok "Patches applied. Exiting (--patches)."; exit 0; fi
        phase3_stubs
        phase4_cmake
        phase5_post_cmake
        phase6_build
        phase7_verify
    fi

    phase8_package
    phase9_scripts
    phase10_dmg

    ok "All phases complete! DMG: $BUILD_DIR/WebKit-${VERSION}-SnowLeopard-x86_64.dmg"
}

main "$@"
