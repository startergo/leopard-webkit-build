    # Prefer Mac/Cocoa/CF variants; penalize foreign-platform ones.
    def score(p):
        s = len(p)
        for frag in ("/cocoa/", "/mac/", "/cf/", "/cg/", "/commoncrypto/"):
            if frag in p: s -= 1000
        for frag in FOREIGN:
            if frag in p: s += 1000
        return s
    return sorted(paths, key=score)[0]
wc_all = {}
for dp, _, files in os.walk(wc):
    for fn in files:
        if fn.endswith(".h"):
            wc_all.setdefault(fn, []).append(os.path.join(dp, fn))
flat = 0
skipped_local = 0
skipped_foreign = 0
skipped_staged = 0
skipped_oninclude = 0
wc_inc_dirs = set(
    os.path.abspath(d) for d in os.environ.get("WC_INC_DIRS", "").split(":") if d
)
for base, paths in wc_all.items():
    if base in local_owned:
        skipped_local += 1
        continue
    # Drop foreign-only headers entirely (no Mac-relevant variant).
    non_foreign = [p for p in paths if not any(fr in p for fr in FOREIGN)]
    chosen_pool = non_foreign if non_foreign else None
    if chosen_pool is None:
        skipped_foreign += 1
        continue
    real = prefer_mac(chosen_pool)
    # If the chosen real header lives in a directory already on WebCore's -I
    # include path, a bare #include "X.h" resolves to it DIRECTLY. Adding a flat
    # ForwardingHeaders/X redirect then creates a SECOND physical path to the
    # same header; #pragma once keys on path so the two do not dedupe and the
    # contents redefine (DictationContextType, etc.) in any TU that also pulls
    # the cmake <WebCore/X> copy. Only emit a flat redirect when the header's
    # directory is NOT already an -I dir (genuine gap, e.g. some cocoa subdirs).
    real_dir = os.path.dirname(os.path.abspath(real))
    dst = os.path.join(fwd, base)
    # Skip the flat redirect ONLY when BOTH hold:
    #  (1) the header's dir is on WebCore's -I path (WebCore resolves it
    #      directly, so the flat redirect is redundant for WebCore), AND
    #  (2) cmake stages a ForwardingHeaders/WebCore/<base> copy (so WebKitLegacy
    #      -- which has NO WebCore subdirs -- resolves it via <WebCore/base>).
    # If (1) holds but (2) does not, WebKitLegacy has no other way to find the
    # header (no subdir, no copy) and DOES need the flat redirect (e.g.
    # AttributedString.h). If (1) is false, WebCore itself needs the flat
    # redirect (e.g. ExtensionsGLANGLE.h, whose angle dir is not on the path).
    # Skipping only when both hold removes the redundant second physical path
    # that made #pragma once fail (DictationContextType) without starving any
    # consumer that genuinely needs the redirect.
    if real_dir in wc_inc_dirs and base in wc_copy_names:
        skipped_oninclude += 1
        continue
    if not os.path.exists(dst):
        open(dst, "w").write('#include "%s"\n' % real)
        flat += 1
print("[leopard] created %d flat WebCore forwarding headers "
      "(skipped %d JSC/WTF/bmalloc-owned, %d foreign-only, %d cmake-staged)"
      % (flat, skipped_local, skipped_foreign, skipped_staged))
print("[leopard]   (also skipped %d already on WebCore -I path)" % skipped_oninclude)

# (b) ANGLE redirects for every <ANGLE/X> include across WebCore.
import re
needed = set()
for dp, _, files in os.walk(wc):
    for fn in files:
        if fn.endswith((".cpp", ".mm", ".h")):
            try:
                t = open(os.path.join(dp, fn)).read()
            except Exception:
                continue
            for m in re.findall(r'#\s*(?:include|import)\s*<ANGLE/([^>]+)>', t):
                needed.add(m)
# index real ANGLE headers by basename
angle_real = {}
for dp, _, files in os.walk(angle):
    for fn in files:
        if fn.endswith(".h"):
            angle_real.setdefault(fn, os.path.join(dp, fn))
adst = os.path.join(fwd, "ANGLE")
os.makedirs(adst, exist_ok=True)
amade = 0
for h in needed:
    real = angle_real.get(os.path.basename(h))
    if real:
        d = os.path.join(adst, os.path.dirname(h))
        if d: os.makedirs(d, exist_ok=True)
        open(os.path.join(adst, h), "w").write('#include "%s"\n' % real)
        amade += 1
print("[leopard] created %d ANGLE forwarding headers" % amade)

# (b2) Framework-prefixed redirects. WebCore/WebKitLegacy do
# #include <Prefix/Foo.h> for internal headers (e.g. <JavaScriptCore/
# JSExportMacros.h>, <pal/ExportMacros.h> via WebCore/config.h) that cmake's
# forwarding-header pass (public API only) omits. For each (prefix, real-root)
# pair, scan WebCore for <prefix/X> includes and fill in every missing redirect.
prefix_roots = [
    ("JavaScriptCore", os.path.abspath(os.environ["JSC_ROOT"])),
    ("pal",            os.path.abspath(os.environ["PAL_ROOT"])),
    ("bmalloc",        os.path.abspath(os.environ["BMALLOC_ROOT"])),
    ("wtf",            os.path.abspath(os.environ["WTF_ROOT"])),
    ("WebCore",        wc),
]
for prefix, proot in prefix_roots:
    if not os.path.isdir(proot):
        print("[leopard] %s root missing: %s" % (prefix, proot))
        continue
    needed = set()
    scan_dirs = [wc]
    wkl = os.path.abspath(os.environ.get("WKL_ROOT", ""))
    if wkl and os.path.isdir(wkl):
        scan_dirs.append(wkl)
    for sd in scan_dirs:
        for dp, _, files in os.walk(sd):
            for fn in files:
                if fn.endswith((".cpp", ".mm", ".h")):
                    try:
                        t = open(os.path.join(dp, fn)).read()
                    except Exception:
                        continue
                    for m in re.findall(r'#\s*(?:include|import)\s*<' + re.escape(prefix) + r'/([^>]+)>', t):
                        needed.add(os.path.basename(m))
    preal = {}
    for dp, _, files in os.walk(proot):
        for fn in files:
            if fn.endswith(".h"):
                preal.setdefault(fn, os.path.join(dp, fn))
    pdst = os.path.join(fwd, prefix)
    os.makedirs(pdst, exist_ok=True)
    pmade = 0
    for h in needed:
        dst = os.path.join(pdst, h)
        if not os.path.exists(dst):
            real = preal.get(h)
            if real:
                open(dst, "w").write('#include "%s"\n' % real)
                pmade += 1
    print("[leopard] created %d %s forwarding headers" % (pmade, prefix))

# (c) Copy GLES2/KHR/EGL header subtrees so <GLES2/...> etc. resolve.
import shutil
copied = 0
for sub in ("GLES2", "GLES", "GLES3", "KHR", "EGL"):
    s = os.path.join(angle, "include", sub)
    d = os.path.join(fwd, sub)
    if os.path.isdir(s) and not os.path.isdir(d):
        shutil.copytree(s, d)
        copied += 1
print("[leopard] copied %d ANGLE include subtrees (GLES2/KHR/EGL/...)" % copied)
PYGEN
        info "  generated WebCore/ANGLE forwarding headers + GL include trees"
    fi

    # [leopard] UserAgentScripts.h is an optional generated DerivedSource (gated
    # by WebCore_USER_AGENT_SCRIPTS, which our config leaves unset, so cmake
    # emits no rule for it). RenderThemeMac.mm #imports it unconditionally, but
    # nothing we compile references its symbols (QuickTimePluginReplacement.mm
    # is not in the build), so we only need the HEADER to exist for the import
    # to resolve. Generate it with the same make-js-file-arrays.py the proven
    # 605 build used, into DerivedSources/WebCore (already on the -I path).
    local UAS_H="$BUILD_DIR/DerivedSources/WebCore/UserAgentScripts.h"
    local UAS_CPP="$BUILD_DIR/DerivedSources/WebCore/UserAgentScriptsData.cpp"
    local MJFA="$SOURCE_DIR/Source/JavaScriptCore/Scripts/make-js-file-arrays.py"
    local QTPR_JS="$SOURCE_DIR/Source/WebCore/Modules/plugins/QuickTimePluginReplacement.js"
    if [ ! -f "$UAS_H" ] && [ -f "$MJFA" ] && [ -f "$QTPR_JS" ]; then
        local PY27="/Library/Frameworks/Python.framework/Versions/2.7/bin/python2.7"
        [ -x "$PY27" ] || PY27="python3"
        mkdir -p "$BUILD_DIR/DerivedSources/WebCore"
        ( cd "$BUILD_DIR/Source/WebCore" && "$PY27" "$MJFA" -n WebCore "$UAS_H" "$UAS_CPP" "$QTPR_JS" )             && info "  generated UserAgentScripts.h ($(wc -c < "$UAS_H" | tr -d ' ') bytes)"             || warn "  UserAgentScripts.h generation failed (RenderThemeMac.mm may not compile)"
    fi

    touch "$stamp"
    ok "Post-cmake fixes applied"
}

# ── Phase 6: Build ─────────────────────────────────────────────────────────
phase6_build() {
    info "Phase 6: Building with ninja..."
    cd "$BUILD_DIR"

    local NCPUS="$(sysctl -n hw.ncpu)"
    local JOBS="$(( NCPUS * 9 / 10 ))"; [ "$JOBS" -ge 1 ] || JOBS=1
    info "  Using -j${JOBS} (hw.ncpu=${NCPUS})"
    local BUILD_LOG="$BUILD_DIR/ninja-build.log"; rm -f "$BUILD_LOG"

    # Defensive re-scrub: CMake may auto-reconfigure between phase 5 and here
    # (ninja re-runs cmake when a CMakeLists.txt / *.cmake / the cache is stale),
    # which REGENERATES build.ninja and re-adds the host-only / restricted
    # frameworks phase 5 stripped.  Re-apply the same scrub idempotently so the
    # build never sees `-framework AVFoundation` (absent on 10.6) or
    # `-framework CFNetwork` (LC_SUB_CLIENT, not an allowed client).  No-op when
    # build.ninja is already clean (the grep finds nothing).
    local NINJA="$BUILD_DIR/build.ninja"
    if [ -f "$NINJA" ] && grep -qE '\-framework (AVFoundation|AVFAudio|Metal|DataDetectorsCore|Lookup|CFNetwork)( |$)' "$NINJA"; then
        for fw in AVFoundation AVFAudio Metal DataDetectorsCore Lookup; do
            sed -i '' "s|/System/Library/Frameworks/$fw.framework||g; s|/System/Library/PrivateFrameworks/$fw.framework||g" "$NINJA"
            sed -i '' "s/-framework $fw //g; s/-framework $fw\$//g" "$NINJA"
        done
        sed -i '' 's|-iframework /Versions/Current/Frameworks||g' "$NINJA"
        sed -i '' 's/-framework CFNetwork //g; s/-framework CFNetwork$//g' "$NINJA"
        info "  re-scrubbed framework links (CMake reconfigure detected)"
    fi

    # Capture ninja's exit code DIRECTLY (not via PIPESTATUS): a `grep ... || true`
    # suffix on the pipe resets PIPESTATUS and masks the real failure. Live output
    # goes to the log via tee; RC comes from the pipeline's first stage.
    # Build ONLY the deliverable frameworks (JavaScriptCore, WebCore,
    # WebKitLegacy).  The default `all` target also builds Tools/tests —
    # MiniBrowser, testapi, WebKitTestRunner, DumpRenderTree, MallocBench —
    # which are NOT part of the WebKit.framework deliverable.  MiniBrowser's Mac
    # variant is a WK2 client (imports WebKit/WK*.h) and cannot build under
    # ENABLE_WEBKIT=OFF; testapi/DumpRenderTree use 10.7+ ObjC features.  None
    # are needed, so build the three framework targets explicitly.
    set +e
    ninja -j"$JOBS" JavaScriptCore WebCore WebKitLegacy 2>&1 | tee "$BUILD_LOG"
    local RC=${PIPESTATUS[0]}
    set -e

    if [ "$RC" -ne 0 ]; then
        err "Ninja build failed (exit $RC). Full log: $BUILD_LOG"
        grep -E 'FAILED:|error:|fatal error:|ld:|Undefined symbol|duplicate symbol|linker command failed|cannot find|file not found' "$BUILD_LOG" 2>/dev/null \
            | grep -v 'note: *in instantiation\|note: *explicitly cast' | head -60 || tail -40 "$BUILD_LOG"
        warn "First-pass 605 builds surface additional 10.6-SDK breaks (audit §16)."
        warn "Iterate patches/overlay in patches-610/ and re-run: ./build_605.sh --clean"
        exit 1
    fi

    # Best-effort: relink JSC to export the WTF mutex symbols Safari expects.
    # Guarded so a failed relink restores the default-linked binary (never leaves
    # the framework binary deleted).
    if [ -f "lib/libWTF.a" ]; then
        info "  Relinking JSC with WTF mutex symbol exports..."
        local JSC_LK=$(ninja -t commands lib/JavaScriptCore.framework/Versions/A/JavaScriptCore 2>/dev/null | tail -1)
        if [ -n "$JSC_LK" ]; then
            rm -f lib/JavaScriptCore.framework/Versions/A/JavaScriptCore
            if eval "$(echo "$JSC_LK" | sed 's|lib/libWTF.a|-Wl,-u,__ZN3WTF36lockAtomicallyInitializedStaticMutexEv -Wl,-u,__ZN3WTF38unlockAtomicallyInitializedStaticMutexEv lib/libWTF.a|')" >>"$BUILD_LOG" 2>&1; then
                info "  JSC relink complete"
            else
                warn "  JSC mutex-export relink failed; restoring default link"
                ninja lib/JavaScriptCore.framework/Versions/A/JavaScriptCore >>"$BUILD_LOG" 2>&1 || true
            fi
        fi
    fi

    ok "Build complete"
}

# ── Phase 7: Verify ────────────────────────────────────────────────────────
phase7_verify() {
    info "Phase 7: Verifying build outputs..."
    local ALL_OK=true
    local FRAMEWORKS=( JavaScriptCore WebCore WebKitLegacy )
    for FW in "${FRAMEWORKS[@]}"; do
        local P="$BUILD_DIR/lib/$FW.framework/Versions/A/$FW"
        [ -f "$P" ] || P="$BUILD_DIR/lib/$FW.framework/$FW"
        if [ -f "$P" ]; then
            local SZ=$(ls -lh "$P" | awk '{print $5}')
            if file "$P" | grep -q 'x86_64'; then ok "$FW.framework: $SZ (x86_64)"
            else warn "$FW.framework: $SZ (unexpected arch)"; ALL_OK=false; fi
        else err "$FW.framework: NOT FOUND"; ALL_OK=false; fi
    done
    $ALL_OK || { err "Framework verification failed"; exit 1; }
    ok "All target frameworks built (ENABLE_WEBKIT=OFF → no WK2 WebKit.framework)"
}

