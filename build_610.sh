#!/bin/bash
for k in WebKitAcceleratedCompositingEnabled WebKitAccelerated2dCanvasEnabled WebKitAcceleratedDrawingEnabled WebKitCanvasUsesAcceleratedDrawing WebKitWebGLEnabled WebKitHiddenPageDOMTimerThrottlingEnabled WebKitHiddenPageCSSAnimationSuspensionEnabled; do
    defaults delete com.apple.Safari "$k" 2>/dev/null
done
echo "Advanced features reverted to defaults."
EOF

    cat > "$S/install.command" <<'EOF'
#!/bin/bash
DIR="$(cd "$(dirname "$0")" && pwd)"
echo "Installing WebKit.app to /Applications..."
rm -rf "/Applications/WebKit.app"
cp -R "$DIR/WebKit.app" "/Applications/WebKit.app"
echo "Done."
echo ""
echo "IMPORTANT: this build uses the WebKit1 (WK1) engine and only loads into"
echo "Safari 5.0.5 (the last pure-WebKit1 Safari). If /Applications/Safari.app is"
echo "Safari 5.1.x (WK2), WebKit.app will launch Safari but the new engine will"
echo "NOT be used. Replace Safari 5.1.10 with Safari 5.0.5 in /Applications first."
echo ""
echo "Then launch /Applications/WebKit.app and run 'enable advanced features.command'."
EOF

    cat > "$S/uninstall.command" <<'EOF'
#!/bin/bash
echo "Removing /Applications/WebKit.app..."
rm -rf "/Applications/WebKit.app"
echo "Done. WebKit has been uninstalled."
EOF

    chmod +x "$S/"*.command
    ok "Install scripts created in $S/"
}

# ── Phase 10: Build DMG ────────────────────────────────────────────────────
phase10_dmg() {
    info "Phase 10: Building DMG..."
    local NAME="WebKit-${VERSION}-SnowLeopard-x86_64"
    local DMG="$BUILD_DIR/$NAME.dmg"
    local STAGE="$BUILD_DIR/dmg_staging"
    rm -rf "$STAGE" "$DMG"; mkdir -p "$STAGE"
    cp -R "$BUILD_DIR/WebKit.app" "$STAGE/"
    cp -R "$BUILD_DIR/scripts/"*.command "$STAGE/" 2>/dev/null || true

    cat > "$STAGE/Readme.txt" <<READEOF
WebKit ${VERSION} for Mac OS X 10.6 Snow Leopard (x86_64)
========================================================

Modern WebKit (safari-610.1.15-branch) built for Snow Leopard with minimal,
branch-specific compatibility patches for the 10.6 SDK.

INSTALLATION
------------
1. Run "install.command" (or drag WebKit.app to /Applications).
2. Run "enable advanced features.command" to enable WebGL, accelerated
   compositing, etc. in Safari.
3. Launch /Applications/WebKit.app — it starts Safari using the updated
   WebKit frameworks.

UNINSTALLATION
--------------
Run "uninstall.command" or delete /Applications/WebKit.app.

WHAT'S INCLUDED
---------------
- JavaScriptCore.framework  (${VERSION})
- WebCore.framework         (${VERSION})
- WebKit.framework          (${VERSION}, WebKitLegacy in the WebKit slot — 10.6 dyld)
- WebKitLegacy.framework    (${VERSION})
- libc++ / libc++abi        (5.0.1)
- ICU                       (55.1)

NOTES
-----
ENABLE_WEBKIT=OFF: the modern WK2/WebKit tree is not built (it needs APIs and a
process model unavailable on 10.6). This package targets the WebKit1 (WK1) API
served by WebKitLegacy. IMPORTANT: only Safari 5.0.5 (the last pure-WebKit1
Safari) can load it — Safari 5.1.x uses WK2 and will NOT use this build. Replace
the stock 10.6 Safari 5.1.10 with Safari 5.0.5 in /Applications first.
WebGL/WebGL2, indexed DB, crypto, and accelerated compositing are enabled;
media features needing AVFoundation (10.7+) and WebGPU/Metal (10.11+) are off.

REQUIREMENTS
------------
- Mac OS X 10.6 Snow Leopard (x86_64)
- Safari 5.0.5 in /Applications (WebKit1). NOT Safari 5.1.x (WK2). Replace the
  stock 10.6 Safari 5.1.10 with Safari 5.0.5 before launching WebKit.app.
READEOF

    # makehybrid → HFS+/Apple partition scheme, mountable on 10.6 (no APFS/GPT).
    info "  Creating disk image..."
    local HYBRID="$BUILD_DIR/${NAME}_hybrid.dmg"; rm -f "$HYBRID"
    hdiutil makehybrid -hfs -hfs-volume-name "WebKit Snow Leopard" -o "$HYBRID" "$STAGE"
    hdiutil convert "$HYBRID" -format UDZO -o "$DMG" -imagekey zlib-level=9
    rm -f "$HYBRID"; rm -rf "$STAGE"
    ok "DMG created: $DMG ($(ls -lh "$DMG" | awk '{print $5}'))"
}

# ── Main ───────────────────────────────────────────────────────────────────
main() {
    echo "========================================================"
    echo "  WebKit 605 (${VERSION}) for Mac OS X 10.6 Snow Leopard"
    echo "  Cross-compiling: $(uname -m) → x86_64   (ENABLE_WEBKIT=OFF)"
    echo "========================================================"
    echo ""

    if $CLEAN; then
        info "Cleaning 605 build tree..."
        rm -rf "$BUILD_DIR"; mkdir -p "$BUILD_DIR" "$STAMP_DIR" "$BUILD_DIR/cmake"
        ( cd "$SOURCE_DIR" && git checkout -- . 2>/dev/null && git clean -fd -- Source/ 2>/dev/null ) || true
        info "Clean complete."
    fi

    if $PACKAGE_ONLY; then
        info "Skipping phases 0-7 (--package-only)"
    else
        phase0_prerequisites
        phase1_icu
        phase1_libcxx
        phase2_patches
        if $PATCHES_ONLY; then ok "Patches applied. Exiting (--patches)."; exit 0; fi
        phase3_stubs
        phase4_cmake
        phase5_post_cmake
        phase6_build
        phase7_verify
    fi

    phase8_package
    phase9_scripts
    phase10_dmg

    ok "All phases complete! DMG: $BUILD_DIR/WebKit-${VERSION}-SnowLeopard-x86_64.dmg"
}

main "$@"
