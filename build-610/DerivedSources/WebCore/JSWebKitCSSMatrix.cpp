        return space;
    static_assert(std::is_base_of_v<JSC::JSDestructibleObject, JSWebKitCSSMatrix> || !JSWebKitCSSMatrix::needsDestruction);
    if constexpr (std::is_base_of_v<JSC::JSDestructibleObject, JSWebKitCSSMatrix>)
        spaces.m_subspaceForWebKitCSSMatrix = makeUnique<IsoSubspace> ISO_SUBSPACE_INIT(vm.heap, vm.destructibleObjectHeapCellType.get(), JSWebKitCSSMatrix);
