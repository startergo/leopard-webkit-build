        return space;
    static_assert(std::is_base_of_v<JSC::JSDestructibleObject, JSHTMLInputElement> || !JSHTMLInputElement::needsDestruction);
    if constexpr (std::is_base_of_v<JSC::JSDestructibleObject, JSHTMLInputElement>)
        spaces.m_subspaceForHTMLInputElement = makeUnique<IsoSubspace> ISO_SUBSPACE_INIT(vm.heap, vm.destructibleObjectHeapCellType.get(), JSHTMLInputElement);
