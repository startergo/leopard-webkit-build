        return space;
    static_assert(std::is_base_of_v<JSC::JSDestructibleObject, JSHTMLAppletElement> || !JSHTMLAppletElement::needsDestruction);
    if constexpr (std::is_base_of_v<JSC::JSDestructibleObject, JSHTMLAppletElement>)
        spaces.m_subspaceForHTMLAppletElement = makeUnique<IsoSubspace> ISO_SUBSPACE_INIT(vm.heap, vm.destructibleObjectHeapCellType.get(), JSHTMLAppletElement);
    else
        spaces.m_subspaceForHTMLAppletElement = makeUnique<IsoSubspace> ISO_SUBSPACE_INIT(vm.heap, vm.cellHeapCellType.get(), JSHTMLAppletElement);
    auto* space = spaces.m_subspaceForHTMLAppletElement.get();
