        return space;
    static_assert(std::is_base_of_v<JSC::JSDestructibleObject, JSCharacterData> || !JSCharacterData::needsDestruction);
    if constexpr (std::is_base_of_v<JSC::JSDestructibleObject, JSCharacterData>)
        spaces.m_subspaceForCharacterData = makeUnique<IsoSubspace> ISO_SUBSPACE_INIT(vm.heap, vm.destructibleObjectHeapCellType.get(), JSCharacterData);
    else
        spaces.m_subspaceForCharacterData = makeUnique<IsoSubspace> ISO_SUBSPACE_INIT(vm.heap, vm.cellHeapCellType.get(), JSCharacterData);
